-- Aplicar manualmente, con autorización del dueño de la BD.
--
-- Contexto verificado en docs/schema-export.sql (dump real):
--   * ecommerce_ventas.ecom_pedido YA EXISTE con
--     (id_pedido, id_cliente, fecha_pedido, monto_total, estado).
--   * ecommerce_ventas.ecom_detalle_pedido YA EXISTE con
--     id_producto INTEGER y PK id_detalle_ped.
--     -> Cambiar id_producto a uuid rompe inventario.inv_producto,
--        ecommerce_ventas.ecom_detalle_carrito y ecommerce_ventas.ecom_catalogo.
--   * ecommerce_ventas.ecom_pedido_outbox NO EXISTE.
--
-- Los CREATE TABLE IF NOT EXISTS usan el DDL real: en la BD real son no-op y sólo
-- sirven para levantar una base vacía en el test aislado (PG_TEST_URL).
-- El efecto real en la BD compartida son los ALTER TABLE, el outbox y los índices.
-- Re-ejecutable.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1) Tablas base con el DDL real (no-op si ya existen)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ecommerce_ventas.ecom_pedido (
  id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY,
  id_cliente INTEGER NOT NULL,
  fecha_pedido DATE NOT NULL DEFAULT CURRENT_DATE,
  monto_total NUMERIC(14,2) NOT NULL,
  estado VARCHAR(50) NOT NULL,
  CONSTRAINT pedido_pkey PRIMARY KEY (id_pedido),
  CONSTRAINT pedido_monto_total_check CHECK (monto_total >= 0)
);

CREATE TABLE IF NOT EXISTS ecommerce_ventas.ecom_detalle_pedido (
  id_detalle_ped INTEGER GENERATED BY DEFAULT AS IDENTITY,
  id_pedido INTEGER NOT NULL,
  id_producto INTEGER NOT NULL,
  cantidad INTEGER NOT NULL,
  precio_unitario NUMERIC(14,2) NOT NULL,
  CONSTRAINT detalle_pedido_pkey PRIMARY KEY (id_detalle_ped),
  CONSTRAINT detalle_pedido_cantidad_check CHECK (cantidad > 0),
  CONSTRAINT detalle_pedido_precio_unitario_check CHECK (precio_unitario >= 0),
  CONSTRAINT fk_detalle_pedido_pedido FOREIGN KEY (id_pedido)
    REFERENCES ecommerce_ventas.ecom_pedido(id_pedido)
);

-- ---------------------------------------------------------------------------
-- 2) Datos de envío y de pago que el checkout envía y el repositorio inserta
-- ---------------------------------------------------------------------------

ALTER TABLE ecommerce_ventas.ecom_pedido
  ADD COLUMN IF NOT EXISTS direccion_entrega VARCHAR(250),
  ADD COLUMN IF NOT EXISTS comuna_entrega VARCHAR(250),
  ADD COLUMN IF NOT EXISTS ciudad_entrega VARCHAR(250),
  ADD COLUMN IF NOT EXISTS telefono_contacto VARCHAR(250),
  ADD COLUMN IF NOT EXISTS metodo_pago VARCHAR(30),
  ADD COLUMN IF NOT EXISTS observaciones TEXT;

-- ---------------------------------------------------------------------------
-- 3) Outbox de idempotencia + payload para CRM
--    status usa los valores que devuelve crmService: 'pending' | 'synced' | 'mock'
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ecommerce_ventas.ecom_pedido_outbox (
  id_pedido INTEGER PRIMARY KEY
    REFERENCES ecommerce_ventas.ecom_pedido(id_pedido),
  id_cliente INTEGER NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  fingerprint TEXT NOT NULL,
  payload JSONB NOT NULL,
  status VARCHAR(20) NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ecom_pedido_outbox_status_check
    CHECK (status IN ('pending','synced','mock')),
  CONSTRAINT ecom_pedido_outbox_cliente_key UNIQUE (id_cliente, idempotency_key)
);

-- ---------------------------------------------------------------------------
-- 4) Índices
-- ---------------------------------------------------------------------------

-- Detalle por pedido (postgresOrderRepository.get). Ya existe el índice por
-- id_producto (idx_detalle_pedido_producto), pero no por id_pedido.
CREATE INDEX IF NOT EXISTS ecom_detalle_pedido_pedido_idx
  ON ecommerce_ventas.ecom_detalle_pedido(id_pedido);

-- Historial por cliente. Ya existe idx_pedido_cliente(id_cliente); este compuesto
-- cubre el ORDER BY fecha_pedido DESC, id_pedido DESC de list/listByCustomer.
CREATE INDEX IF NOT EXISTS ecom_pedido_cliente_fecha_idx
  ON ecommerce_ventas.ecom_pedido(id_cliente, fecha_pedido DESC, id_pedido DESC);

COMMIT;

